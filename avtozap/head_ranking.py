"""Ранжирование по головному слову запроса. Согласовано с проектом.

Задача. И в азербайджанском, и в русском тип детали несёт **последнее** слово
фразы, а принадлежность — предшествующее: ``X-in Y`` = «Y, принадлежащий X».
Поставленный Retriever V2 такого приоритета не различает и на конструкциях вида
``çəninin qapağı`` (крышка бака) поднимал наверх бак, а не крышку.

Как решаем. Отдельным проходом ПОВЕРХ вендорного ретривера, не трогая его код:
кандидат, чьё собственное имя содержит головное слово запроса, получает
небольшую надбавку. Вендорный ``match()`` не затрагивается вовсе, поэтому
контрольный прогон проекта (485/70/149) остаётся тем же по построению.

Почему «последнее слово, известное словарю», а не просто последнее. В живых
заявках хвостом часто идёт марка производителя: ``Qabaq sağ sol çaşka
lenforderle``. Слово ``lenforderle`` словарю неизвестно, головой становится
``çaşka`` — то, что покупатель на самом деле просит.

Что дал замер
-------------
На эталоне 469 правило поднимает долю «правильный код на первом месте» с 323 до
334 заявок (+11). На эталоне 200, который в подборе не участвовал, — без
изменений: 114 и там, и там. Состав shortlist не меняется ни на одном наборе,
то есть потолок цепочки правило не двигает — только порядок внутри списка.

Прирост скромнее, чем ожидалось в сентябре, и причина понятна: словарь версии
01.09 уже закрыл большинство конструкций «владелец/деталь» выверенными
контекстными правилами (``qapi + kilid motoru`` → EL-041 и подобными). Общему
правилу осталась та часть, до которой у отдельных правил руки не дошли.

Что пробовал и убрал
--------------------
**Штраф кандидату без головного слова** — казался симметричным дополнением к
надбавке, но замер его не подтвердил: с ним rank#1 падал с 334 до 319, то есть
хуже, чем вообще без правила. Понижать всё, что не совпало головой, слишком
грубо: у многих деталей имя в словаре не содержит того слова, которым их зовёт
покупатель, и держится такой кандидат как раз на синонимах.

**Большая надбавка.** 0.02 даёт +6, 0.06 уже −4, 0.10 — −9. Надбавка не должна
перебивать точное совпадение фразы целиком, поэтому она намеренно мала.
"""

from __future__ import annotations

#: Надбавка кандидату, чьё ИМЯ содержит головное слово запроса.
#: Значение подобрано замером на эталоне 469 (см. докстринг): 0.01 — максимум,
#: дальше правило начинает перебивать точные совпадения и вредить.
HEAD_BOOST = 0.01

#: Головным словом считаем только осмысленно длинное слово.
MIN_HEAD_LENGTH = 3


def head_token(tokens: list[str], is_known) -> str | None:
    """Головное слово фразы: последнее слово, известное словарю.

    ``is_known`` — предикат «словарь знает такое слово». Хвостовые марки
    (``lenforderle``, ``limforder``) словарю неизвестны и головой не считаются.
    """
    for token in reversed(tokens):
        if len(token) >= MIN_HEAD_LENGTH and is_known(token):
            return token
    return None


def rerank(candidates, head: str | None, name_tokens_of, matches) -> None:
    """Поднять кандидатов, совпавших головным словом. Меняет список на месте.

    ``candidates``     — объекты со свойствами ``external_code`` и ``score``;
    ``name_tokens_of`` — слова собственного ИМЕНИ детали (без синонимов);
    ``matches``        — мягкое сравнение двух слов.

    Сравниваем именно с именем, а не с синонимами: синонимы у листа общие, и по
    ним крышка бака неотличима от самого бака — а различить их и есть задача.
    """
    if not head or not candidates:
        return
    for candidate in candidates:
        own_words = name_tokens_of(candidate.external_code)
        if any(matches(head, word) for word in own_words):
            candidate.score = round(min(0.9999, candidate.score + HEAD_BOOST), 4)
            candidate.reason = f"{candidate.reason} | head:{head}"
    candidates.sort(key=lambda c: (-c.score, c.external_code))
