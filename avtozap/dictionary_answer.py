"""Точный термин словаря сильнее отказа арбитра.

Что показал живой прогон 469. Арбитр отказался 20 раз, и в 13 случаях
правильный ответ стоял у него первым в списке, причём не по догадке, а **точным
термином словаря**: ``Vintilyatorun datçiki``, ``On alin susesi``,
``avtopasos``, ``Stop``. Модель рассуждала о смысле и не решалась, тогда как в
словаре заказчика ровно эта фраза записана и указывает ровно на одну деталь.

Промпт Arbiter V3 заморожен, и трогать его нельзя. Но выбрасывать ответ,
который дал сам словарь, — это не осторожность, а потеря: код берётся из
данных заказчика, а не придумывается.

Где правило НЕ работает — это важнее того, где работает
--------------------------------------------------------
Правило намеренно узкое, и каждое ограничение куплено замером:

* **только однодетальные заявки.** На наборе 200 есть 27 заявок, где верный
  ответ — отказ, и больше половины из них многодетальные. Без этого
  ограничения правило отвечало бы на 12 из 27 вместо отказа, с ним — на 4.
* **точный термин должен покрывать запрос.** Совпадение по обрывку длинной
  фразы не считается: в ``Start Stop düyməsinin oboyması. Kod BT4Z-11584-BA``
  находится термин, ведущий в «Проводка/разъёмы», хотя просят кнопку. Порог
  покрытия ``0.6`` убирает такие случаи полностью — риск на отказных заявках
  падает с 4 до нуля.
* **неоднозначные термины словаря не трогаем.** Если сработало правило
  ``AMBIGUOUS_RULES``, переспрос остаётся переспросом.
* **код обязан быть в shortlist.** Правило V2 валидатора действует и здесь.

Чего это стоит, по замеру на живом прогоне 469:

===============  ===========  =====================
порог покрытия   верно / 469  риск на 27 отказных
===============  ===========  =====================
без правила      428          —
0.0              439          3
0.5              438          1
**0.6**          **436**      **0**
1.0              434          0
===============  ===========  =====================

Взят 0.6 — точка, где на отказных заявках риск нулевой. Порог вынесен в
``config.DICTIONARY_ANSWER_MIN_COVERAGE``: после прогона набора 200 его можно
будет подвинуть по живым данным, а не по этой таблице.

Ответ, полученный так, помечается в отчёте (``answered_by``) — чтобы всегда
было видно, сколько ответов дала модель, а сколько словарь.
"""

from __future__ import annotations

import re

from .config import DICTIONARY_ANSWER_MIN_COVERAGE
from .retriever import content_tokens

#: Причина вендорного ретривера для точного совпадения фразы: ``exact:<фраза>``.
_EXACT_REASON = re.compile(r"exact:([^|]+)")

#: Метка источника ответа в отчёте.
SOURCE_ARBITER = "arbiter"
SOURCE_DICTIONARY = "dictionary_exact"


def exact_phrase(reason: str) -> str | None:
    """Фраза, которой кандидат совпал точно, или ``None``."""
    found = _EXACT_REASON.search(reason or "")
    return found.group(1).strip() if found else None


def coverage(phrase: str, item_raw: str) -> float:
    """Какую долю значимых слов запроса покрывает точная фраза."""
    tokens = content_tokens(item_raw or "")
    if not tokens or not phrase:
        return 0.0
    return len(phrase.split()) / len(tokens)


def resolve(item_raw: str, candidates, canonical,
            min_coverage: float = DICTIONARY_ANSWER_MIN_COVERAGE) -> str | None:
    """Код, который словарь даёт на этот запрос точным термином, или ``None``.

    ``candidates`` — shortlist ретривера в его порядке; берётся только первый:
    если точным термином совпал не он, значит что-то другое оказалось сильнее,
    и однозначности нет. ``canonical`` сводит код-дубль к живому.
    """
    if not candidates:
        return None
    top = candidates[0]
    phrase = exact_phrase(getattr(top, "reason", "") or "")
    if not phrase:
        return None
    if coverage(phrase, item_raw) < min_coverage:
        return None
    return canonical(getattr(top, "external_code", None))
